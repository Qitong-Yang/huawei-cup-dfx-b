"""Parse HarmonyOS jscrash logs into a structured CrashContext.

Handles the formats seen in the contest data:
  * standard faultlogger output (``Error name:`` / ``Error message:`` / ``Stacktrace:``);
  * hand-written variants using ``Error type:`` / ``Description:`` and ``Key: value`` spacing;
  * stack frames with full module paths, a ``file:`` prefix, or bare file names.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)

# Header fields we keep. Values are taken from the first occurrence before the HiLog section,
# because HiLog repeats "Error name:" etc. with a log prefix.
_HEADER_KEYS = {
    "module name": "module_name",
    "process name": "process_name",
    "build info": "build_info",
    "device info": "device_info",
    "timestamp": "timestamp",
    "reason": "reason",
    "error name": "error_name",
    "error type": "error_type",
    "error message": "error_message",
    "description": "description",
}
_HEADER_RE = re.compile(r"^\s*([A-Za-z][A-Za-z ]*?)\s*:\s*(.*?)\s*$")

# "at <func> (<location>:<line>:<col>)"
_FRAME_RE = re.compile(r"^\s*at\s+(?P<func>.*?)\s*\((?P<loc>[^()]*?):(?P<line>\d+):(?P<col>\d+)\)\s*$")
_PAGE_RE = re.compile(r"^\s*(?P<time>\d{2}:\d{2}:\d{2}\.\d+)\s+(?P<page>\S.*?)\s*$")

# Sections that end the JS stack trace.
_STACK_END_RE = re.compile(
    r"^\s*(HiLog|HybridStack|SourceMap|SourceCode|Variables|Stacktrace \(native\)|"
    r"Steps to reproduce|Root cause|Fix|=+)\s*:?\s*$",
    re.IGNORECASE,
)

# Sections that leak the answer in some hand-written logs; never part of a real faultlogger log.
LEAKY_SECTIONS = ("Root cause", "Fix")
# Answer headings may carry their text on the same line and need not indent the body.
_LEAK_HEADER_RE = re.compile(r"^\s*(?:root[\s_-]*cause|fix)\s*[:：]", re.IGNORECASE)
_SAFE_SECTION_RE = re.compile(
    r"^\s*(?:Stacktrace(?: \(native\))?|HiLog|HybridStack|SourceMap|SourceCode|"
    r"Variables|Page switch history|Steps to reproduce)\s*[:：]\s*$",
    re.IGNORECASE,
)

_SOURCE_EXTS = (".ets", ".ts", ".js")


@dataclass(frozen=True)
class StackFrame:
    """One JS stack frame."""

    func: str
    path: str  # normalized: forward slashes, no "file:" prefix
    line: int
    col: int
    raw: str
    is_business: bool


@dataclass(frozen=True)
class CrashContext:
    """Structured view of one jscrash log."""

    error_name: str
    error_message: str
    module_name: str
    build_info: str
    timestamp: str
    frames: tuple[StackFrame, ...]
    is_standard_format: bool = False  # real faultlogger output ("Generated by HiviewDFX")
    page_history: tuple[str, ...] = field(default_factory=tuple)
    warnings: tuple[str, ...] = field(default_factory=tuple)

    @property
    def business_frames(self) -> tuple[StackFrame, ...]:
        return tuple(f for f in self.frames if f.is_business)

    @property
    def top_business_frame(self) -> StackFrame | None:
        frames = self.business_frames
        return frames[0] if frames else None


# On-device install paths, e.g. /data/storage/el1/bundle/entry/ets/pages/A.ets: app code.
_DEVICE_APP_PATH_RE = re.compile(r"^/data/storage/el\d/")
_SYSTEM_PATH_RE = re.compile(r"^(/system/|/usr\d*/|obj/|internal/)|/obj/foundation/|ArkUI internal")


def decode_log_bytes(data: bytes) -> str:
    """Decode a log file, honouring UTF-16/UTF-8 byte-order marks."""
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16", errors="replace")
    if data.startswith(b"\xef\xbb\xbf"):
        return data[3:].decode("utf-8", errors="replace")
    return data.decode("utf-8", errors="replace")


def normalize_path(loc: str) -> str:
    """Strip ``file:`` / ``file://`` prefixes and normalize separators."""
    path = loc.strip().replace("\\", "/")
    if path.startswith("file://"):
        path = path[len("file://"):]
    elif path.startswith("file:"):
        path = path[len("file:"):]
    return path.removeprefix("./")


def is_business_path(path: str) -> bool:
    """True for app source frames; False for ArkUI/runtime frames."""
    if not path.endswith(_SOURCE_EXTS):
        return False
    if _DEVICE_APP_PATH_RE.match(path):
        return True
    return not (path.startswith("/") or _SYSTEM_PATH_RE.search(path))


def _parse_header(lines: list[str]) -> dict[str, str]:
    header: dict[str, str] = {}
    for line in lines:
        if line.strip().startswith("HiLog"):
            break
        match = _HEADER_RE.match(line)
        if not match:
            continue
        key = _HEADER_KEYS.get(match.group(1).lower())
        if key and key not in header and match.group(2):
            header[key] = match.group(2)
    return header


def _parse_frames(lines: list[str]) -> list[StackFrame]:
    frames: list[StackFrame] = []
    in_stack = False
    for line in lines:
        stripped = line.strip()
        if stripped.lower() == "stacktrace:":
            if frames:  # a second Stacktrace block (e.g. repeated in HiLog) is ignored
                break
            in_stack = True
            continue
        if not in_stack:
            continue
        if _STACK_END_RE.match(line) or _LEAK_HEADER_RE.match(line):
            break
        match = _FRAME_RE.match(line)
        if not match:
            continue
        path = normalize_path(match.group("loc"))
        frames.append(
            StackFrame(
                func=match.group("func").strip(),
                path=path,
                line=int(match.group("line")),
                col=int(match.group("col")),
                raw=stripped,
                is_business=is_business_path(path),
            )
        )
    return frames


def _parse_page_history(lines: list[str]) -> list[str]:
    pages: list[str] = []
    in_section = False
    for line in lines:
        if line.strip().startswith("Page switch history"):
            in_section = True
            continue
        if not in_section:
            continue
        if not line.strip():
            continue
        match = _PAGE_RE.match(line)
        if not match:
            break
        pages.append(match.group("page"))
    return pages


def parse_crash_log(text: str) -> CrashContext:
    """Parse the text of one jscrash log."""
    lines = text.splitlines()
    header = _parse_header(lines)
    warnings: list[str] = []

    error_name = header.get("error_name") or header.get("error_type") or header.get("reason", "")
    error_message = header.get("error_message") or header.get("description", "")
    if not header.get("error_name"):
        warnings.append("missing 'Error name' field; fell back to Error type/Reason")
    if not error_message:
        warnings.append("missing error message")

    frames = _parse_frames(lines)
    if not frames:
        warnings.append("no stack frames parsed")
    elif not any(f.is_business for f in frames):
        warnings.append("no business frames in stack")

    if any(_LEAK_HEADER_RE.match(line) for line in lines):
        warnings.append("log contains non-standard answer sections (Root cause / Fix)")

    return CrashContext(
        error_name=error_name,
        error_message=error_message,
        module_name=header.get("module_name") or header.get("process_name", ""),
        build_info=header.get("build_info", ""),
        timestamp=header.get("timestamp", ""),
        frames=tuple(frames),
        is_standard_format="Generated by HiviewDFX" in text[:200],
        page_history=tuple(_parse_page_history(lines)),
        warnings=tuple(warnings),
    )


def strip_leaky_sections(text: str) -> str:
    """Remove answer sections, resuming only at a recognized crash-log header.

    Indentation, blank lines, arbitrary ``Key:`` text and separators do not end an
    answer section. This is redaction of known labels, not proof that arbitrary
    free text is free of semantic answers; the sandbox also scans known markers.
    """
    out: list[str] = []
    skipping = False
    for line in text.splitlines(keepends=True):
        if _LEAK_HEADER_RE.match(line):
            skipping = True
            continue
        if skipping:
            header = _HEADER_RE.match(line)
            known_header = header is not None and header.group(1).lower() in _HEADER_KEYS
            if not (known_header or _SAFE_SECTION_RE.match(line)):
                continue
            skipping = False
        out.append(line)
    return "".join(out)
