"""Unit tests for dfx_repair.locate.rules (positive and negative cases)."""

from pathlib import Path

from dfx_repair.ingest import parse_crash_log
from dfx_repair.locate import locate_with_rules
from dfx_repair.locate.rules.align import align_crash_line
from dfx_repair.retrieve import SourceIndex

SORT_SRC = """export class VM {
  public swap(a: number, b: number) {
    const items = this.items;
    if (a >= items.length) {
      return;
    }
    let x = items[a].order;
    let y = items[b].order;
  }
}
"""

SORT_SRC_CHECKED = SORT_SRC.replace("if (a >= items.length)", "if (a >= items.length || b >= items.length)")

PCM_SRC = """export class Pcm {
  parse(buffer: ArrayBuffer) {
    const view = new DataView(buffer);
    const total = buffer.byteLength / 4;
    for (let i = 0; i <= total; i++) {
      const off = i * 4;
      const v = view.getFloat32(off, true);
    }
  }
}
"""


def _log(path: str, line: int, col: int, name: str, msg: str) -> str:
    return (f"Generated by HiviewDFX@OpenHarmony\nError name:{name}\nError message:{msg}\n"
            f"Stacktrace:\n    at fn mod ({path}:{line}:{col})\n")


def _run(tmp_path: Path, rel: str, src: str, log: str):
    target = tmp_path / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(src, encoding="utf-8")
    return locate_with_rules("C", parse_crash_log(log), SourceIndex(tmp_path))


def test_partial_bounds_check_fires(tmp_path: Path):
    col = SORT_SRC.splitlines()[7].index("order") + 1
    log = _log("a/VM.ets", 8, col, "TypeError", "Cannot read property order of undefined")
    result = _run(tmp_path, "a/VM.ets", SORT_SRC, log)
    assert result.primary.start_line == 4 and result.primary.role == "missing_check"
    assert result.root_cause_locations[-1].start_line == 8  # crash line kept as fallback


def test_partial_bounds_check_silent_when_both_checked(tmp_path: Path):
    col = SORT_SRC_CHECKED.splitlines()[7].index("order") + 1
    log = _log("a/VM.ets", 8, col, "TypeError", "Cannot read property order of undefined")
    result = _run(tmp_path, "a/VM.ets", SORT_SRC_CHECKED, log)
    assert result.primary.start_line == 8 and len(result.root_cause_locations) == 1


def test_loop_off_by_one_fires_and_respects_strict_bound(tmp_path: Path):
    log = _log("a/Pcm.ets", 7, 17, "RangeError", "getIndex +elementSize > viewSize")
    assert _run(tmp_path, "a/Pcm.ets", PCM_SRC, log).primary.start_line == 5
    strict = PCM_SRC.replace("i <= total", "i < total")
    assert _run(tmp_path / "s", "a/Pcm.ets", strict, log).primary.start_line == 7


def test_alignment_moves_off_comment_and_keeps_plausible_line():
    lines = tuple(
        "    // pick the first record as template\n"
        "    const tpl = list[0];\n"
        "    const order = Object.keys(tpl);\n".splitlines()
    )
    ctx = parse_crash_log(_log("a/VM.ets", 1, 16, "TypeError",
                               "Cannot convert a UNDEFINED value to a JSObject"))
    moved = align_crash_line(ctx, "a/VM.ets", 1, 16, lines)
    assert (moved.line, moved.aligned_from) == (3, 1)
    kept = align_crash_line(ctx, "a/VM.ets", 3, 16, lines)
    assert (kept.line, kept.aligned_from) == (3, None)
