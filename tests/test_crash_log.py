def test_standard_log_fields_and_frames():
    ctx = parse_crash_log(STANDARD_LOG)
    assert ctx.is_standard_format
    assert ctx.module_name == "zhyy.1.xxxxxx"
    assert ctx.error_name == "TypeError"  # HiLog's repeated "Error name" is ignored
    assert ctx.error_message == "Cannot read property sortNum of undefined"
    assert [f.is_business for f in ctx.frames] == [True, False, True]
    top = ctx.top_business_frame
    assert top is not None and (top.line, top.col) == (83, 33)
    assert top.path.endswith("viewmodels/ResourceManageVM.ets")
    assert ctx.page_history == ("/ets/pages/Index:MoneyTrackPage", "/ets/pages/Index:Main")
    assert ctx.warnings == ()


def test_handwritten_log_falls_back_and_flags_leak():
    ctx = parse_crash_log(HANDWRITTEN_LOG)
    assert ctx.error_name == "TypeError"
    assert "SharePicker" in ctx.error_message
    assert ctx.top_business_frame.path == "VideoPlayPage.ets"
    assert len(ctx.frames) == 2  # frames stop before "Root cause:"
    assert any("Root cause" in w for w in ctx.warnings)


def test_strip_leaky_sections_removes_answer_only():
    cleaned = strip_leaky_sections(HANDWRITTEN_LOG)
    assert "Root cause" not in cleaned and "new SharePicker" not in cleaned
    assert "at shareEvent (VideoPlayPage.ets:72:24)" in cleaned
    assert parse_crash_log(cleaned).top_business_frame.line == 72


def test_device_paths_and_process_name():
    ctx = parse_crash_log(DEVICE_PATH_LOG)
    assert ctx.module_name == "kdwl.1.xxxxxx"
    assert [f.is_business for f in ctx.frames] == [True, False]
    assert ctx.top_business_frame.path == "/data/storage/el1/bundle/entry/ets/viewModels/ExpressPageVM.ets"


def test_normalize_and_classify_paths():
    assert normalize_path("file:components/a/B.ets") == "components/a/B.ets"
    assert normalize_path("a\\b\\C.ets") == "a/b/C.ets"
    assert normalize_path("./x/Y.ets") == "x/Y.ets"
    assert is_business_path("commons/component/src/main/ets/utils/PropUtil.js")
    assert not is_business_path("/usr1/hmos/out/obj/foundation/arkui/stateMgmt.js")
    assert not is_business_path("ArkUI internal")
    assert not is_business_path("components/a/B.json")


def test_decode_utf16_with_bom():
    text = "Error name:SyntaxError\r\n"
    assert decode_log_bytes(text.encode("utf-16")) == text
    assert decode_log_bytes(b"\xef\xbb\xbf" + text.encode("utf-8")) == text
