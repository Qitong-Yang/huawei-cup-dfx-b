import json
from pathlib import Path

import pytest
from tests.llm_fakes import FakeBackend

from dfx_repair.ingest import parse_crash_log
from dfx_repair.llm import load_prompt
from dfx_repair.locate import LlmLocator, locate_with_rules
from dfx_repair.locate.llm import adopt
from dfx_repair.retrieve import SourceIndex

VM_SRC = """export class VM {
  public swap(a: number, b: number) {
    const items = this.items;
    if (a >= items.length) {
      return;
    }
    let x = items[a].order;
    let y = items[b].order;
  }
}
"""
MOCK_SRC = """export const ITEMS = [
  { order: 1 },
  { order: 2 },
  { order: 3 },
  make(1,
    2,
    3),
  { order: 4 },
  { order: 5 },
  { order: 6 },
  undefined,
];
"""
CRASH_LINE = 8
COL = VM_SRC.splitlines()[7].index("order") + 1
LOG = ("Generated by HiviewDFX@OpenHarmony\nError name:TypeError\n"
       "Error message:Cannot read property order of undefined\n"
       f"Stacktrace:\n    at swap vm (a/VM.ets:{CRASH_LINE}:{COL})\n")
UPSTREAM_OK = {
    "hypothesis": "upstream", "file": "a/Mock.ets", "line": 11, "quoted_line": "undefined,",
    "evidence_file": "a/VM.ets", "evidence_line": 8, "evidence_quote": "let y = items[b].order;",
    "origin_file": "a/Mock.ets", "origin_line": 11, "origin_quote": "undefined,",
    "reasoning": "the mock list holds undefined",
}
CRASH_LINE_BAD_EVIDENCE = {**UPSTREAM_OK, "hypothesis": "crash_line", "file": "a/VM.ets",
                           "line": 8, "quoted_line": "let y = items[b].order;",
                           "evidence_quote": "nope"}
MULTILINE = {**UPSTREAM_OK, "line": 6, "quoted_line": "2,"}


@pytest.fixture
def sandbox(tmp_path: Path) -> Path:
    case = tmp_path / "case"
    (case / "app" / "a").mkdir(parents=True)
    (case / "app" / "a" / "VM.ets").write_text(VM_SRC, encoding="utf-8")
    (case / "app" / "a" / "Mock.ets").write_text(MOCK_SRC, encoding="utf-8")
    (case / "crash.log").write_text(LOG, encoding="utf-8")
    return case


def run(sandbox: Path, answer: dict | None, **kw):
    ctx = parse_crash_log(LOG)
    index = SourceIndex(sandbox / "app")
    backend = FakeBackend(answer=answer, **kw)
    return LlmLocator(backend)("C1", ctx, index), locate_with_rules("C1", ctx, index), backend


def test_adopts_upstream_with_valid_quotes(sandbox):
    r, rule, _ = run(sandbox, UPSTREAM_OK)
    assert rule.primary.start_line == 4  # partial bounds rule fires; crash line is 8
    assert r.method == "rules+llm" and r.status == "CANDIDATE"
    assert (r.primary.file, r.primary.start_line) == ("a/Mock.ets", 11)
    assert r.primary.role == "root_cause"
    roles = [loc.role for loc in r.root_cause_locations]
    assert roles == ["root_cause", "statement_span", "rule_answer", "crash_line"]
    assert r.root_cause_locations[-1].start_line == CRASH_LINE
    assert r.crash_location == rule.crash_location
    assert any("llm reasoning" in e for e in r.evidence)


def test_crash_line_answer_needs_no_evidence(sandbox):
    r, _, _ = run(sandbox, CRASH_LINE_BAD_EVIDENCE)
    assert r.primary.start_line == CRASH_LINE and r.primary.file == "a/VM.ets"


def test_hypothesis_label_is_ignored(sandbox):
    r, rule, _ = run(sandbox, {**UPSTREAM_OK, "hypothesis": "crash_line", "evidence_quote": "x"})
    assert r.primary == rule.primary and "llm fallback: evidence mismatch" in r.assumptions


def test_evidence_on_the_answer_line_does_not_count(sandbox):
    r, rule, _ = run(sandbox, {**UPSTREAM_OK, "evidence_file": "a/Mock.ets",
                               "evidence_line": 11, "evidence_quote": "undefined,"})
    assert r.primary == rule.primary and "llm fallback: evidence mismatch" in r.assumptions


def test_fabricated_quote_falls_back_to_rules(sandbox):
    r, rule, _ = run(sandbox, {**UPSTREAM_OK, "quoted_line": "made up"})
    assert r.primary == rule.primary and "llm fallback: quote mismatch" in r.assumptions
    assert r.root_cause_locations == rule.root_cause_locations and r.method == "rules+llm"


def test_backend_error_keeps_rule_answer_and_status(sandbox):
    r, rule, _ = run(sandbox, None, error="timeout 900s")
    assert r.primary == rule.primary and r.status == rule.status
    assert "llm fallback: no answer: timeout 900s" in r.assumptions


def test_over_budget_answer_is_kept_and_marked(sandbox):
    r, _, _ = run(sandbox, UPSTREAM_OK, over_budget=True)
    assert r.primary.file == "a/Mock.ets" and "over token budget" in r.assumptions


def test_adopt_drops_over_budget_answer_when_configured(sandbox):
    _, rule, _ = run(sandbox, None)
    checks = {"quote_matches": True, "evidence_matches": True, "origin_matches": True}
    assert adopt(UPSTREAM_OK, checks, rule, over_budget=True, keep_over_budget=False) == (
        False, "over budget (answer dropped)")


def test_multiline_answer_adds_statement_span(sandbox):
    r, _, _ = run(sandbox, MULTILINE)
    spans = [loc for loc in r.root_cause_locations if loc.role == "statement_span"]
    assert r.primary.start_line == 6 and spans and spans[0].end_line > spans[0].start_line


def test_answer_path_is_normalized(sandbox):
    r, _, _ = run(sandbox, {**UPSTREAM_OK, "file": "./a/Mock.ets"})
    assert r.primary.file == "a/Mock.ets"


def test_prompt_contains_log_rule_view_and_window(sandbox):
    _, _, fb = run(sandbox, UPSTREAM_OK)
    p = fb.request.user_prompt
    assert p.startswith("Crash log (sanitized):\n" + LOG)
    assert '"crash_location"' in p and f"{CRASH_LINE}:     let y = items[b].order;" in p
    assert "Code around the crash (a/VM.ets):\n1: export class VM {" in p
    assert p.endswith("is the bad value/code produced upstream? Then submit.")
    assert fb.request.system_prompt == load_prompt()[0]
    assert fb.request.app_root == (sandbox / "app").resolve()


def test_missing_crash_log_raises(sandbox):
    (sandbox / "crash.log").unlink()
    with pytest.raises(FileNotFoundError):
        run(sandbox, UPSTREAM_OK)


def test_record_and_stats(sandbox, tmp_path, monkeypatch):
    monkeypatch.setenv("ANTHROPIC_API_KEY", "sk-test-SECRET")
    ctx, index = parse_crash_log(LOG), SourceIndex(sandbox / "app")
    loc = LlmLocator(FakeBackend(answer=UPSTREAM_OK), record_dir=tmp_path / "llm")
    loc("C@1", ctx, index)
    text = (tmp_path / "llm" / "C_1.json").read_text(encoding="utf-8")
    rec = json.loads(text)
    assert "12e09676" in text and "SECRET" not in text
    assert rec["adopted"] is True and rec["checks"]["quote_matches"] is True
    assert rec["transcript"] == [{"type": "fake"}] and "transcript" not in rec["session"]
    assert loc.stats == [{"case_id": "C@1", "adopted": True, "reason": "adopted",
                          "tokens": 12_000, "cache_read_tokens": 6000, "turns": 3,
                          "seconds": 1.0, "over_budget": False, "error": None}]


class _Exploding(FakeBackend):
    def run(self, request):
        raise OSError("cleanup failed")


def test_backend_exception_falls_back_to_rules(sandbox):
    ctx, index = parse_crash_log(LOG), SourceIndex(sandbox / "app")
    loc = LlmLocator(_Exploding())
    r = loc("C1", ctx, index)
    rule = locate_with_rules("C1", ctx, index)
    assert r.primary == rule.primary and r.method == "rules+llm"
    assert "llm fallback: no answer: OSError('cleanup failed')" in r.assumptions
    assert loc.stats[0]["error"] == "OSError('cleanup failed')"
